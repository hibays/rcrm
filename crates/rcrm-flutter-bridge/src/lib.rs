/// Callback invoked from a spawned thread when metadata parsing completes.
/// `result` is a JSON C string (never null) that Dart must free with
/// `rcrm_free_string`. `ctx` is the opaque user pointer passed to the async
/// call (an integer request id).
type MetadataCallback = unsafe extern "C" fn(*mut c_char, *mut std::ffi::c_void);

ffi_exports! {
	/// Asynchronous metadata parse: media bytes → JSON.
	///
	/// One entry point for both kinds of source — EXIF for images, track info for
	/// video/audio containers — dispatched by the container header unless
	/// `kind_hint` says otherwise (0 = auto, 1 = image, 2 = track). The JSON shape
	/// is documented in `metadata.rs`.
	///
	/// The hand-off copies nothing: Dart fetches the head **straight into a
	/// Rust-allocated buffer** and passes that pointer, so the bytes travel socket
	/// → native buffer → parser without ever being duplicated. Rust owns the
	/// allocation from the start and frees it when the parse finishes, so Dart must
	/// not touch it after this call.
	///
	/// There is deliberately no capacity parameter. The `Vec` is rebuilt from `len`
	/// alone, so the only sound input is a buffer allocated with exactly `len`
	/// bytes; taking the capacity from the caller instead would let a wrong value
	/// free the wrong layout, and no caller-supplied number can be checked inside
	/// this function. Dart enforces the "exactly `len` bytes" half by type
	/// (`NativeTransfer`, `services/native_bytes.dart`): it can only be obtained
	/// from a whole-file fetch, where the allocation and the payload are the same
	/// size.
	///
	/// # Safety
	/// `data` must be a pointer returned by `rcrm_alloc_bytes` for **exactly** `len`
	/// bytes (never a partially filled fixed-size buffer), and must not be used
	/// again from Dart. `callback` may be null (no-op). `ctx` is passed through
	/// verbatim and must stay valid for the duration of the spawned thread (it is
	/// an opaque integer id).
	fallback unit
	pub unsafe fn rcrm_media_metadata_async(
		data: *const u8,
		len: usize,
		kind_hint: u8,
		callback: Option<MetadataCallback>,
		ctx: *mut std::ffi::c_void,
	) {
		// Every rejected call still answers: the JSON is the only channel back,
		// and "no buffer" and "empty input" send a reader to different places.
		if data.is_null() {
			if let Some(cb) = callback {
				let json = str_to_cstring(r#"{"kind":"unknown","error":"no buffer"}"#);
				unsafe { cb(json, ctx) };
			}
			return;
		}
		if len == 0 {
			// Ownership was transferred with the call, so take (and free) it here
			// rather than leak it on a path nobody expects to happen.
			drop(unsafe {
				Box::from_raw(std::ptr::slice_from_raw_parts_mut(
					data.cast_mut().cast::<MaybeUninit<u8>>(),
					0,
				))
			});
			if let Some(cb) = callback {
				let json = str_to_cstring(r#"{"kind":"unknown","error":"empty input"}"#);
				unsafe { cb(json, ctx) };
			}
			return;
		}
		let bytes = unsafe { take_ffi_bytes(data, len) };
		let hint = metadata::KindHint::from_code(kind_hint);
		let ctx_raw = ctx as usize;
		spawn_ffi_job(
			"rcrm_media_metadata_async",
			move || metadata::parse_json(bytes, hint),
			move |json, reason| {
				if let Some(cb) = callback {
					let json = json.unwrap_or_else(|| {
						if reason == "spawn failed" {
							r#"{"kind":"unknown","error":"spawn failed"}"#.to_string()
						} else {
							r#"{"kind":"unknown","error":"parser panicked"}"#.to_string()
						}
					});
					unsafe { cb(str_to_cstring(&json), ctx_raw as *mut std::ffi::c_void) };
				}
			},
			move |reason| {
				if let Some(cb) = callback {
					let json = if reason == "spawn failed" {
						r#"{"kind":"unknown","error":"spawn failed"}"#
					} else {
						r#"{"kind":"unknown","error":"parser panicked"}"#
					};
					unsafe { cb(str_to_cstring(json), ctx_raw as *mut std::ffi::c_void) };
				}
			},
		);
	}
}

