// Unwinding out of `extern "C"` aborts the process, taking the Flutter UI
// with it. Every export is generated by `ffi_exports!` below. Following
// flutter_rust_bridge's handler design the barrier is DOUBLE: an outer catch
// covers the error-reporting path itself (reporting inside an FFI frame can
// panic, which would otherwise unwind across the boundary), while an inner
// catch runs the body. Every async job uses the same shape for delivery.

thread_local! {
	/// The hook only flips a flag: a full `Backtrace::force_capture()` costs
	/// ~4 us and must not be paid by every panic in the process (libraries we
	/// do not own catch panics too). Only the reporter of a guarded export
	/// pays it, once. A `Cell<bool>` has no destructor, unlike `Option<Backtrace>`.
	static PANIC_PENDING: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
	/// `PanicHookInfo::location()` is a cheap `&'static Location` (no stack walk).
	/// Saving it at panic time is what preserves the REAL panic site: the stack
	/// captured later by the reporter is only a catch-site stack, since the
	/// panicking frames have already unwound by then.
	static PANIC_LOCATION: std::cell::Cell<Option<&'static std::panic::Location<'static>>> =
		const { std::cell::Cell::new(None) };
	/// The panic text for THIS caller. `LAST_ERROR` is process-wide and can be
	/// overwritten by a panic on another isolate; Dart reads the error back on
	/// the thread that made the call, so prefer the per-thread copy.
	static LAST_PANIC: RefCell<Option<String>> = const { RefCell::new(None) };
}

/// Install once, before any body can panic: the hook runs at panic time to
/// record the cheap `location()` and flip the flag. The expensive stack is
/// captured later by the reporter. The previous hook is preserved and called.
fn install_panic_hook() {
	static INSTALL: std::sync::Once = std::sync::Once::new();
	INSTALL.call_once(|| {
		let previous = std::panic::take_hook();
		std::panic::set_hook(Box::new(move |info| {
			// Nothing in a panic hook may panic: a nested panic aborts.
			let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
				let _ = PANIC_PENDING.try_with(|flag| flag.set(true));
				let _ = PANIC_LOCATION.try_with(|slot| slot.set(info.location()));
			}));
			let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| previous(info)));
		}));
	});
}

/// Whether this thread panicked since the last guarded call. Consuming the
/// flag discards panics from code we do not report.
fn take_panic_pending() -> bool {
	PANIC_PENDING.try_with(|flag| flag.take()).unwrap_or(false)
}

/// The recorded panic site, consumed together with the pending flag.
fn take_panic_location() -> Option<&'static std::panic::Location<'static>> {
	PANIC_LOCATION.try_with(|slot| slot.take()).ok().flatten()
}

/// The "no result" value for an export's ABI return shape, declared once per
/// export as `fallback token`. A token table, not a trait: no impl per
/// pointer type, and the declaration sits next to the function it describes.
macro_rules! ffi_fallback {
	(unit) => {
		()
	};
	(i32) => {
		-1
	};
	(null) => {
		std::ptr::null_mut()
	};
	(error_json) => {
		$crate::error_json("internal")
	};
}

/// The absolute last resort when even the fallback panicked: no allocation,
/// no formatting — just a value that can cross the ABI without touching the
/// allocator. For string exports this is null (Dart already handles null).
macro_rules! ffi_fallback_simple {
	(unit) => {
		()
	};
	(i32) => {
		-1
	};
	(null) => {
		std::ptr::null_mut()
	};
	(error_json) => {
		std::ptr::null_mut()
	};
}

/// The one error-JSON literal for every string-returning export's panic path.
fn error_json(reason: &str) -> *mut c_char {
	let json = serde_json::json!({ "error": reason }).to_string();
	str_to_cstring(&json)
}

/// Panic text from the payload, shared by every reporter including the startup
/// thread, so both paths tell Dart the same kind of thing.
fn panic_text(payload: &(dyn std::any::Any + Send)) -> String {
	if let Some(s) = payload.downcast_ref::<&str>() {
		(*s).to_string()
	} else if let Some(s) = payload.downcast_ref::<String>() {
		s.clone()
	} else {
		"unknown panic".to_string()
	}
}

/// Put a caught panic where Dart can read it: `getLastErrorMessage()` reads
/// LAST_ERROR. `log_error!` alone is not enough — the app sets log level 0.
/// The backtrace comes from the hook installed before the body ran.
pub(crate) fn record_ffi_panic(name: &'static str, payload: &(dyn std::any::Any + Send)) {
	let text = panic_text(payload);
	let site = match take_panic_location() {
		Some(loc) => format!(
			"{name} panicked at {}:{}:{}: {text}",
			loc.file(),
			loc.line(),
			loc.column()
		),
		None => format!("{name} panicked: {text}"),
	};
	let message = if take_panic_pending() {
		// The only place that pays for a full stack, and only for a panic we
		// actually report to Dart. The panicking frames are already unwound, so
		// label this honestly — the real site is the `location()` above.
		format!(
			"{site}\ncatch-site stack (panic frames already unwound):\n{}",
			Backtrace::force_capture()
		)
	} else {
		site
	};
	let _ = LAST_PANIC.try_with(|cell| {
		let _ = cell
			.try_borrow_mut()
			.map(|mut slot| *slot = Some(message.clone()));
	});
	server::set_error(message.as_str());
	rcrm_core::log_error!("[bridge] {message}");
}

/// What Dart sees from `rcrm_last_error()`: a panic recorded on this thread,
/// otherwise the ordinary process-wide error.
fn last_error_message() -> *mut c_char {
	LAST_PANIC
		.try_with(|cell| cell.borrow().clone())
		.ok()
		.flatten()
		.map_or_else(server::last_error, |text| str_to_cstring(&text))
}

/// The double panic barrier for every synchronous export. The outer catch is
/// the "reporting must not unwind across FFI" guard from FRB's handler design;
/// each reporting step is caught on its own as well. `fallback` is `Fn` for the
/// normal failure value; a separate non-allocating `simple` handles the case
/// where even that fallback panicked.
fn ffi_call<T>(
	name: &'static str,
	on_panic: impl FnOnce(),
	body: impl FnOnce() -> T,
	fallback: impl Fn() -> T,
	simple: impl FnOnce() -> T,
) -> T {
	install_panic_hook();
	let _ = take_panic_pending(); // discard a panic outside a guarded export
	let _ = take_panic_location(); // and its site
	// Every export opens a fresh per-thread error window — except the one that
	// READS it. Clearing there would silently fall back to the global error.
	if name != "rcrm_last_error" {
		let _ = LAST_PANIC.try_with(|cell| cell.borrow_mut().take());
	}
	let outcome =
		std::panic::catch_unwind(std::panic::AssertUnwindSafe(
			|| match std::panic::catch_unwind(std::panic::AssertUnwindSafe(body)) {
				Ok(value) => Ok(value),
				Err(payload) => {
					let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
						record_ffi_panic(name, payload.as_ref());
					}));
					let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(on_panic));
					Err(())
				}
			},
		));
	match outcome {
		Ok(Ok(value)) => value,
		// Either the body panicked and was reported, or reporting itself failed.
		// The value still has to cross the ABI, so build it under a catch too.
		Ok(Err(())) | Err(_) => std::panic::catch_unwind(std::panic::AssertUnwindSafe(&fallback))
			.unwrap_or_else(|_| simple()), // never allocates or formats
	}
}

/// Deliver one answer; if the export's callback panics, fall back to a
/// degraded callback that needs no job result. This is what actually keeps the
/// "exactly once" promise: swallowing a panicking delivery would leave the
/// Dart completer pending until its timeout.
fn deliver_guarded<T, D, F>(deliver: &D, degraded: &F, result: Option<T>, reason: &'static str)
where
	D: Fn(Option<T>, &'static str),
	F: Fn(&'static str),
{
	if std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| deliver(result, reason))).is_err() {
		let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| degraded(reason)));
	}
}

/// Spawn one worker and answer exactly once: on success, on panic, and when
/// the thread could not be created. `reason` is "ok", "panic" or "spawn
/// failed" — metadata needs the last two apart, decoders do not.
fn spawn_ffi_job<T, D, F>(
	name: &'static str,
	job: impl FnOnce() -> T + Send + 'static,
	deliver: D,
	degraded: F,
) where
	// The job's result never crosses a thread boundary: `deliver` is called
	// inside the worker, so WebpBuf's raw pointer needs no `Send` impl.
	T: 'static,
	D: Fn(Option<T>, &'static str) + Send + 'static,
	// Every degraded callback only captures Copy values (an optional function
	// pointer and the opaque request id), so Clone is allocation-free here.
	// It must also handle "spawn failed": that path uses it directly.
	F: Fn(&'static str) + Clone + Send + 'static,
{
	install_panic_hook();
	// The job's primary delivery is owned by the single worker; no Arc needed.
	// The degraded copy stays on this thread for the spawn-failure answer.
	let worker_degraded = degraded.clone();
	let spawned = std::thread::Builder::new().spawn(move || {
		match std::panic::catch_unwind(std::panic::AssertUnwindSafe(job)) {
			Ok(value) => deliver_guarded(&deliver, &worker_degraded, Some(value), "ok"),
			Err(payload) => {
				let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
					record_ffi_panic(name, payload.as_ref());
				}));
				deliver_guarded(&deliver, &worker_degraded, None, "panic");
			}
		}
	});
	// A thread-creation failure never ran the job: answer on this thread with
	// the degraded callback, which produces the same failure shape as the
	// primary one would have.
	if spawned.is_err() {
		server::set_error(format!("{name}: failed to spawn worker thread"));
		rcrm_core::log_error!("[bridge] {name}: failed to spawn worker thread");
		let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| degraded("spawn failed")));
	}
}

/// Generate the `extern "C"` shell from a plain function body. `return` inside
/// the body now means what it reads as: return from the export. Attributes
/// (docs, `cfg`) are passed through; an optional `on_panic { … }` clause after
/// the body runs that export's own failure path before the declared fallback.
macro_rules! ffi_exports {
	(
		$(
			$(#[$attr:meta])*
			fallback $fb:ident
			pub unsafe fn $name:ident ( $($arg:ident : $arg_ty:ty),* $(,)? )
			$( -> $ret:ty )?
			$body:block
			$( on_panic $on_panic:block )?
		)*
	) => {
		$(
			$(#[$attr])*
			#[unsafe(no_mangle)]
			pub unsafe extern "C" fn $name($($arg: $arg_ty),*) $( -> $ret )? {
				$crate::ffi_call(
					stringify!($name),
					|| { $($on_panic;)? },
					|| $body,
					|| ffi_fallback!($fb),
					|| ffi_fallback_simple!($fb),
				)
			}
		)*
	};
}

