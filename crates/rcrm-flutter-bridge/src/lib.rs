#[cfg(all(test, feature = "mobile-decode"))]
mod tests {
	use std::sync::atomic::{AtomicUsize, Ordering};

	// Callback state, shared with the C-ABI callback below.
	static CALLBACK_CALLED: AtomicUsize = AtomicUsize::new(0);
	static CALLBACK_RESULT_NULL: AtomicUsize = AtomicUsize::new(0);

	unsafe extern "C" fn on_decode(
		result: *mut crate::decode::DecodeBuf,
		ctx: *mut std::ffi::c_void,
	) {
		// ctx is the request id passed through.
		let _ = ctx;
		CALLBACK_CALLED.fetch_add(1, Ordering::SeqCst);
		if result.is_null() {
			CALLBACK_RESULT_NULL.fetch_add(1, Ordering::SeqCst);
		}
	}

	/// The null-guard added to the async FFI must reject a null / zero-length
	/// buffer BEFORE Vec::from_raw_parts (which is UB on a null pointer), while
	/// still resolving the Dart completer via the callback with a null result.
	#[test]
	fn async_decode_rejects_null_input() {
		unsafe {
			crate::rcrm_decode_avif_async(
				std::ptr::null(),
				0,
				0,
				Some(on_decode),
				std::ptr::null_mut(),
			);
			crate::rcrm_decode_jxl_async(
				std::ptr::null(),
				0,
				0,
				Some(on_decode),
				std::ptr::null_mut(),
			);
			// The HEIC export shares this contract and used to be missing here, so
			// a regression in its null guard went unnoticed.
			crate::rcrm_decode_heic_async(
				std::ptr::null(),
				0,
				0,
				Some(on_decode),
				std::ptr::null_mut(),
			);
		}
		// Callbacks fire on spawned threads; give them a moment to run.
		std::thread::sleep(std::time::Duration::from_millis(200));
		assert_eq!(
			CALLBACK_CALLED.load(Ordering::SeqCst),
			3,
			"all three callbacks must fire"
		);
		assert_eq!(
			CALLBACK_RESULT_NULL.load(Ordering::SeqCst),
			3,
			"null input must yield a null result (no crash / no UB)"
		);
	}
}

// =======================
// Tests — metadata FFI callback contract
// =======================

/// Dart stores a completer per request and ONLY the callback can complete it,
/// so "the callback fires exactly once, whatever the input" is the contract
/// this pins. A parsers' panic is covered by the `catch_unwind` in the FFI;
/// forcing nom-exif to panic is not reproducible, so the reachable paths
/// (garbage bytes, empty input) are what the tests drive.
#[cfg(test)]
mod metadata_ffi_tests {
	use std::sync::mpsc;
	use std::time::Duration;

	/// Hands `bytes` to the FFI the way Dart does: a buffer Rust will free by
	/// rebuilding the `Vec` from the length alone. The ABI requires an
	/// allocation of exactly that many bytes, so there is no slack to give:
	/// `into_ffi_buffer` builds the exact size, and the length it returns IS the
	/// capacity Dart guaranteed.
	fn into_ffi_buffer(bytes: &[u8]) -> (*const u8, usize) {
		if bytes.is_empty() {
			return (std::ptr::null(), 0);
		}
		let ptr = unsafe { crate::rcrm_alloc_bytes(bytes.len()) };
		assert!(!ptr.is_null(), "test allocation failed");
		// SAFETY: ptr is a non-null allocation of exactly bytes.len() bytes.
		unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len()) };
		(ptr, bytes.len())
	}

	/// Mirrors Dart's `_onParsed`: read the JSON, free it with
	/// `rcrm_free_string`, then deliver it to the waiting test.
	///
	/// `ctx` owns a `Box<Sender>` from `ctx_of`. Rebuilding and dropping it here
	/// keeps the sending half alive until the callback is truly done with it;
	/// borrowing the test's `&Sender` through a raw pointer let the test drop it
	/// while the callback thread was still using it (a real data race).
	unsafe extern "C" fn on_json(json: *mut std::ffi::c_char, ctx: *mut std::ffi::c_void) {
		let text = if json.is_null() {
			String::new()
		} else {
			let s = unsafe { std::ffi::CStr::from_ptr(json) }
				.to_string_lossy()
				.into_owned();
			unsafe { crate::rcrm_free_string(json) };
			s
		};
		// SAFETY: ctx came from ctx_of's Box::into_raw; the export calls the
		// callback exactly once, so this rebuild is the sole owner of the clone.
		let tx = unsafe { Box::from_raw(ctx.cast::<mpsc::Sender<String>>()) };
		let _ = tx.send(text);
	}

	fn ctx_of(tx: &mpsc::Sender<String>) -> *mut std::ffi::c_void {
		// The callback owns this clone; the test's `tx` is only used to receive.
		Box::into_raw(Box::new(tx.clone())).cast()
	}

	#[test]
	fn unparsable_bytes_still_answer() {
		let (tx, rx) = mpsc::channel();
		let (ptr, len) = into_ffi_buffer(&[0u8; 64]);
		unsafe {
			crate::rcrm_media_metadata_async(ptr, len, 0, Some(on_json), ctx_of(&tx));
		}
		let json = rx
			.recv_timeout(Duration::from_secs(5))
			.expect("callback must fire for garbage bytes");
		assert!(json.contains(r#""kind":"unknown""#), "{json}");
		assert!(json.contains("error"), "{json}");
	}

	#[test]
	fn valid_jpeg_reports_an_image() {
		let (tx, rx) = mpsc::channel();
		// SOI + EOI: a real, empty JPEG envelope.
		let (ptr, len) = into_ffi_buffer(&[0xff, 0xd8, 0xff, 0xd9]);
		unsafe {
			crate::rcrm_media_metadata_async(ptr, len, 1, Some(on_json), ctx_of(&tx));
		}
		let json = rx
			.recv_timeout(Duration::from_secs(5))
			.expect("callback must fire for a valid container");
		assert!(json.contains(r#""kind":"image""#), "{json}");
	}

	#[test]
	fn null_and_empty_input_are_answered_on_the_calling_thread() {
		let (tx, rx) = mpsc::channel();
		unsafe {
			crate::rcrm_media_metadata_async(std::ptr::null(), 0, 0, Some(on_json), ctx_of(&tx));
		}
		let json = rx
			.recv_timeout(Duration::from_secs(5))
			.expect("callback must fire for a null buffer");
		assert!(json.contains("no buffer"), "{json}");
	}

	/// The defensive path: `len == 0` with a real, non-null allocation. Rust
	/// takes ownership and reconstructs a zero-length `Box<[MaybeUninit<u8>]>`,
	/// which deliberately deallocates nothing — freeing a size this side was
	/// never told is the unsoundness the ABI removed. This test sends that
	/// contract-violating shape on purpose, then reclaims the original 4096-byte
	/// allocation itself so Miri's leak check stays clean.
	#[test]
	fn an_empty_payload_still_transfers_ownership() {
		let v: Vec<u8> = Vec::with_capacity(4096);
		let ptr = v.as_ptr();
		std::mem::forget(v);
		let (tx, rx) = mpsc::channel();
		unsafe {
			crate::rcrm_media_metadata_async(ptr, 0, 0, Some(on_json), ctx_of(&tx));
		}
		let json = rx
			.recv_timeout(Duration::from_secs(5))
			.expect("callback must fire for an empty payload");
		assert!(json.contains("empty input"), "{json}");
		// SAFETY: the zero-length Box dropped inside the FFI deallocated
		// nothing, so this exact (ptr, capacity) pair is still live.
		unsafe { drop(Vec::from_raw_parts(ptr.cast_mut(), 0, 4096)) };
	}
}

